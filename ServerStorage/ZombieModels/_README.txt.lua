This directory should contain zombie character models.

Required Models (R15 or R6 character rigs with Humanoid):
- Walker.rbxm - Basic zombie type
- Runner.rbxm - Fast zombie type
- Brute.rbxm - Tank/heavy zombie type
- Spitter.rbxm - Ranged attack zombie type
- Boss.rbxm - Boss zombie type

Each model must have:
- Humanoid instance
- HumanoidRootPart
- Proper character rig (R15 recommended for animations)

The game will create basic zombies procedurally if these models are not provided.
